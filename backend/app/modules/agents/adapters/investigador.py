async def run_investigador(state: Dict[str, Any]) -> Dict[str, Any]:
    """
    Investigador Agent — two-stage research pipeline:

    1. Local RAG (Qdrant)   — semantic search of existing knowledge base.
    2. LLM synthesis        — summarise all collected material (optional,
       falls back gracefully if model is too small).
    """
    article_id = state.get("article_id")
    title = state.get("title") or ""
    keywords = state.get("keywords") or []
    log = state.get("_log") or (lambda msg, level="info": None)

    logger.info("Running Investigador for article %s with keywords %s", article_id, keywords)
    log(f"🔑 Keywords: {', '.join(keywords) if keywords else '(ninguna)'}")

    # Build query: title words + unique keywords (deduped, title takes priority)
    title_words = [w.strip(".,;:?!()[]") for w in title.split() if len(w) > 3] if title else []
    kw_words = [k for k in keywords if k.lower() not in {w.lower() for w in title_words}]
    combined_terms = title_words + kw_words
    query_str = " ".join(combined_terms) if combined_terms else "scientific research"
    log(f"🔍 Query de búsqueda: \"{query_str[:100]}\"")

    agent_cfg = (state.get("agent_settings") or {}).get("investigador", {})
    context_hint = (agent_cfg.get("context_hint") or "").strip()

    # semantic_rerank: agent_profile > config.yaml global default
    _agent_rerank = agent_cfg.get("semantic_rerank")
    if _agent_rerank is None:
        semantic_rerank = settings.SCRAPER_SEMANTIC_RERANK
    else:
        semantic_rerank = bool(_agent_rerank)
    if context_hint:
        query_str = f"{context_hint} {query_str}"
        logger.info("Investigador context hint: '%s'", context_hint[:80])
        log(f"💡 Context hint aplicado: \"{context_hint[:80]}\"")

    sources: List[Dict[str, Any]] = []
    research_chunks: List[str] = []

    # Resolve RAG collection
    # El perfil aporta un *bucket*; el proyecto de la ejecución compone la
    # colección real, y así dos proyectos con el mismo perfil no se leen
    # (SPEC-013 / T8.5 / AC6).
    rag_bucket = (agent_cfg.get("rag_collection") or "").strip() or settings.QDRANT_COLLECTION
    rag_collection = collection_for_state(state, rag_bucket)
    rag_top_k = int(agent_cfg.get("rag_top_k") or 0) or settings.RAG_TOP_K
    rag_chunk_size = int(agent_cfg.get("rag_chunk_size") or 0) or settings.RAG_CHUNK_SIZE
    rag_doc_ids = agent_cfg.get("rag_doc_ids") or None
    if isinstance(rag_doc_ids, list) and len(rag_doc_ids) == 0:
        rag_doc_ids = None

    # ── Stage 1: Local RAG ───────────────────────────────────────────────────
    # Search the investigador's own bucket AND the shared library, so documents
    # uploaded to either are found. Explicit doc_ids (selected by the user) take
    # precedence and bypass the agent-bucket filter entirely.
    search_agents = ["investigador", LIBRARY_AGENT]
    backend = await get_rag_backend(settings.QDRANT_URL, settings.QDRANT_API_KEY)
    if rag_doc_ids:
        log(f"🔎 Etapa 1/2 — Buscando en documentos seleccionados ({len(rag_doc_ids)}) "
            f"[backend: {backend}, colección: {rag_collection}]...")
    else:
        log(f"🔎 Etapa 1/2 — Buscando fuentes [backend: {backend}, colección: {rag_collection}, "
            f"buckets: {', '.join(search_agents)}]...")
    try:
        # La búsqueda sale de la capacidad `rag_results` cuando el motor la
        # inyecta, y del import de siempre cuando no (SPEC-013/T8.3/AC8).
        buscar = provider(state, "rag_results", semantic_search_results)
        rag_results = await buscar(
            query=query_str,
            qdrant_url=settings.QDRANT_URL,
            collection=rag_collection,
            agent_name=search_agents,
            ollama_base_url=settings.OLLAMA_BASE_URL,
            embedding_model=settings.OLLAMA_EMBED_MODEL,
            limit=rag_top_k,
            api_key=settings.QDRANT_API_KEY,
            doc_ids=rag_doc_ids,
        )
        # Guard: when the user selected specific documents, never build citations
        # from anything else — even if an upstream fallback ignored the filter.
        if rag_doc_ids:
            allowed = set(rag_doc_ids)
            before = len(rag_results)
            rag_results = [r for r in rag_results if r.get("doc_id") in allowed]
            dropped = before - len(rag_results)
            if dropped:
                log(f"🛡️ Descartados {dropped} fragmento(s) de documentos no seleccionados.")
        if rag_results:
            # Build one citation per unique source document (by doc_id), using the
            # real filename as the title instead of a generic placeholder.
            seen_docs: Dict[str, Dict[str, Any]] = {}
            for index, item in enumerate(rag_results):
                text = item.get("text", "")
                filename = item.get("filename", "")
                doc_id = item.get("doc_id") or f"local-{index}"
                if doc_id not in seen_docs:
                    seen_docs[doc_id] = {
                        "doc_title": (item.get("doc_title") or "").strip(),
                        "doc_authors": (item.get("doc_authors") or "").strip(),
                        "journal": "",
                        "year": "",
                        "doi": "",
                        "url": "",
                        "filename": filename,
                        "snippet": text[:200],
                    }
                label = seen_docs[doc_id]["doc_title"] or _clean_doc_title(filename) or filename
                research_chunks.append(f"[Fuente: {label}] {text}")

            # For documents missing extracted metadata, parse the title/authors
            # from the document's opening text at runtime (no manual backfill).
            for doc_id, src in seen_docs.items():
                if src["doc_title"] and src["doc_authors"]:
                    continue
                try:
                    head = await fetch_doc_head(
                        settings.QDRANT_URL, rag_collection, doc_id, settings.QDRANT_API_KEY
                    )
                    if head:
                        meta = extract_doc_metadata(src["filename"], b"", head)
                        src["doc_title"] = src["doc_title"] or meta.get("title", "")
                        src["doc_authors"] = src["doc_authors"] or meta.get("authors", "")
                except Exception as meta_exc:
                    logger.warning("Runtime metadata extraction failed for %s: %s", doc_id, meta_exc)

            # Finalise the citation fields per document.
            for src in seen_docs.values():
                src["title"] = src.pop("doc_title") or _clean_doc_title(src["filename"]) \
                    or src["filename"] or "Documento"
                src["authors"] = src.pop("doc_authors")

            sources.extend(seen_docs.values())
            with_authors = sum(1 for s in seen_docs.values() if s["authors"])
            log(f"📚 {len(seen_docs)} fuente(s) citables — con autores extraídos: {with_authors}.")
            log(
                f"✅ RAG: {len(rag_results)} fragmento(s) de {len(seen_docs)} documento(s) "
                f"en la colección '{rag_collection}'."
            )
        else:
            log(
                f"ℹ️ Sin resultados RAG en '{rag_collection}'. Verifica que los documentos estén "
                f"subidos al investigador o a la biblioteca compartida, en esa misma colección.",
                "warning",
            )
    except Exception as exc:
        logger.warning("Could not search Qdrant: %s", exc)
        log(f"⚠️ RAG local no disponible: {exc}", "warning")

    # ── Stage 2: LLM synthesis ────────────────────────────────────────────────
    # Always run synthesis — with or without external sources.
    # If no external content was found, the LLM uses its parametric knowledge.
    try:
        from app.platform.llm import (
            call_llm, resolve_agent_model, resolve_agent_temperature,
        )
        from app.core.config import settings as _settings
        model = resolve_agent_model("investigador", state.get("agent_settings"))
        # Temperatura del agente (perfil o ajustes de la ejecución). Hasta ahora
        # se guardaba y no llegaba a ningún proveedor.
        temperature = resolve_agent_temperature("investigador", state.get("agent_settings"))

        # When there are no external sources, use a lightweight model for
        # parametric synthesis to avoid OOM when the next agent loads.
        # The investigador model (often mistral:7b) would stay in VRAM
        # and crash the redactor's KV-cache allocation. This is an on-prem
        # (Ollama) concern only — cloud providers have no local VRAM, and the
        # fallback string is an Ollama model, so it must not be sent elsewhere.
        _SYNTHESIS_FALLBACK_MODEL = "llama3.2:1b"

        if research_chunks:
            log(f"🧠 Etapa 2/2 — Síntesis con LLM ({model}) de {len(research_chunks)} fragmento(s)...")
            synthesis_model = model
            combined = "\n\n---\n\n".join(research_chunks[:8])
            synthesis_prompt = (
                "Eres un investigador científico. Lee el siguiente material de investigación y "
                "elabora un resumen estructurado en español con los hallazgos más relevantes, "
                "incluyendo fuentes cuando estén disponibles. Sé conciso pero completo.\n\n"
                f"MATERIAL RECOPILADO:\n{combined[:6000]}\n\n"
                "RESUMEN DE INVESTIGACIÓN:"
            )
        else:
            # Only swap to the lightweight Ollama model on-prem; on cloud
            # providers keep the resolved (provider-native) model.
            synthesis_model = (
                _SYNTHESIS_FALLBACK_MODEL
                if _settings.LLM_PROVIDER.lower() == "ollama"
                else model
            )
            log(f"🧠 Etapa 2/2 — Sin fuentes locales. Síntesis desde conocimiento paramétrico ({synthesis_model})...")
            kw_str = ", ".join(keywords[:8]) if keywords else query_str
            synthesis_prompt = (
                f"Eres un investigador científico experto. Escribe un resumen de investigación "
                f"en español sobre el siguiente tema: '{query_str}'.\n\n"
                f"Palabras clave: {kw_str}\n\n"
                f"Estructura el resumen con:\n"
                f"- Estado del arte\n- Conceptos fundamentales\n- Aplicaciones y relevancia\n"
                f"- Líneas de investigación actuales\n\n"
                f"RESUMEN DE INVESTIGACIÓN:"
            )

        sintetizar = provider(state, "llm", call_llm)
        synthesis = await sintetizar(
            synthesis_prompt,
            model=synthesis_model,
            timeout=600.0 if research_chunks else 120.0,
            keep_alive=0,   # unload after synthesis — frees VRAM before redactor loads its model
            num_ctx=8192 if research_chunks else 2048,   # more context for multi-source synthesis
            temperature=temperature,
        )
        if synthesis and len(synthesis.split()) > 30:
            research_chunks.append(f"[Síntesis] {synthesis}")
            sources.append({
                "title": f"Síntesis sobre: {query_str[:80]}",
                "url": "synthesis://investigador",
                "snippet": synthesis[:200],
            })
            log(f"✅ Síntesis generada — {len(synthesis.split())} palabras.")
        else:
            log("⚠️ Síntesis LLM vacía o muy corta.", "warning")
    except Exception as exc:
        logger.warning("LLM synthesis failed (non-critical): %s", exc)
        log(f"⚠️ Síntesis LLM no disponible: {exc}", "warning")

    # ── Fallback de último recurso ────────────────────────────────────────────
    if not research_chunks:
        log("⚠️ Sin ningún contenido de investigación generado. Usando contexto mínimo.", "warning")
        research_chunks.append(
            f"[Contexto base] Tema: {query_str}\nPalabras clave: {', '.join(keywords[:8])}\n"
            "No se encontró información en la colección local para este tema. "
            "El redactor debe usar su conocimiento propio para generar el artículo."
        )

    research_data = "\n\n---\n\n".join(research_chunks)
    log(f"📦 Investigación completada: {len(sources)} fuente(s), {len(research_chunks)} fragmento(s).")
    return {"research_data": research_data, "sources": sources}

